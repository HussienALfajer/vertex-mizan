import { describe, expect, it } from 'vitest';
import { amountInWords } from './amount-in-words.js';

/** The amount in words on a printed voucher (S11 "Printing and legal books"); synthetic amounts. */
describe('amountInWords', () => {
  it.each([
    // Zero, and a fraction alone.
    [0n, 'USD', 'فقط صفر دولار أمريكي لا غير'],
    [5n, 'USD', 'فقط خمسة سنتات لا غير'],
    [1n, 'TRY', 'فقط قرش واحد لا غير'],
    // One and two: the noun's own forms.
    [100n, 'USD', 'فقط دولار أمريكي واحد لا غير'],
    [200n, 'USD', 'فقط دولاران أمريكيان لا غير'],
    [100n, 'SYP', 'فقط ليرة سورية جديدة واحدة لا غير'],
    [200n, 'TRY', 'فقط ليرتان تركيتان لا غير'],
    // 3–10: the plural, the number in the other gender.
    [300n, 'USD', 'فقط ثلاثة دولارات أمريكية لا غير'],
    [300n, 'SYP', 'فقط ثلاث ليرات سورية جديدة لا غير'],
    [800n, 'TRY', 'فقط ثماني ليرات تركية لا غير'],
    [1000n, 'USD', 'فقط عشرة دولارات أمريكية لا غير'],
    [1000n, 'TRY', 'فقط عشر ليرات تركية لا غير'],
    // 11–99: the accusative singular.
    [1100n, 'USD', 'فقط أحد عشر دولاراً أمريكياً لا غير'],
    [1100n, 'SYP', 'فقط إحدى عشرة ليرة سورية جديدة لا غير'],
    [1200n, 'USD', 'فقط اثنا عشر دولاراً أمريكياً لا غير'],
    [1500n, 'TRY', 'فقط خمس عشرة ليرة تركية لا غير'],
    [1500n, 'USD', 'فقط خمسة عشر دولاراً أمريكياً لا غير'],
    [2000n, 'USD', 'فقط عشرون دولاراً أمريكياً لا غير'],
    [2100n, 'SYP', 'فقط إحدى وعشرون ليرة سورية جديدة لا غير'],
    [2200n, 'USD', 'فقط اثنان وعشرون دولاراً أمريكياً لا غير'],
    [9900n, 'USD', 'فقط تسعة وتسعون دولاراً أمريكياً لا غير'],
    // 100–999.
    [10000n, 'USD', 'فقط مئة دولار أمريكي لا غير'],
    [20000n, 'USD', 'فقط مئتا دولار أمريكي لا غير'],
    [10100n, 'USD', 'فقط مئة وواحد دولار أمريكي لا غير'],
    [10500n, 'TRY', 'فقط مئة وخمس ليرات تركية لا غير'],
    [25000n, 'USD', 'فقط مئتان وخمسون دولاراً أمريكياً لا غير'],
    [99900n, 'SYP', 'فقط تسعمئة وتسع وتسعون ليرة سورية جديدة لا غير'],
    // Thousands: the spec's example first.
    [150000n, 'USD', 'فقط ألف وخمسمئة دولار أمريكي لا غير'],
    [100000n, 'USD', 'فقط ألف دولار أمريكي لا غير'],
    [200000n, 'USD', 'فقط ألفا دولار أمريكي لا غير'],
    [300000n, 'TRY', 'فقط ثلاثة آلاف ليرة تركية لا غير'],
    [1100000n, 'USD', 'فقط أحد عشر ألف دولار أمريكي لا غير'],
    [3450000n, 'TRY', 'فقط أربعة وثلاثون ألفاً وخمسمئة ليرة تركية لا غير'],
    [20000000n, 'USD', 'فقط مئتا ألف دولار أمريكي لا غير'],
    [25000000n, 'USD', 'فقط مئتان وخمسون ألف دولار أمريكي لا غير'],
    [100300n, 'USD', 'فقط ألف وثلاثة دولارات أمريكية لا غير'],
    // Millions and more.
    [100000000n, 'SYP', 'فقط مليون ليرة سورية جديدة لا غير'],
    [250000000n, 'USD', 'فقط مليونان وخمسمئة ألف دولار أمريكي لا غير'],
    [700000000n, 'USD', 'فقط سبعة ملايين دولار أمريكي لا غير'],
    [100100000n, 'USD', 'فقط مليون وألف دولار أمريكي لا غير'],
    [300000000000n, 'SYP', 'فقط ثلاثة مليارات ليرة سورية جديدة لا غير'],
    // With a fraction.
    [150025n, 'USD', 'فقط ألف وخمسمئة دولار أمريكي وخمسة وعشرون سنتاً لا غير'],
    [101n, 'USD', 'فقط دولار أمريكي واحد وسنت واحد لا غير'],
    [302n, 'SYP', 'فقط ثلاث ليرات سورية جديدة وقرشان لا غير'],
    [1050n, 'TRY', 'فقط عشر ليرات تركية وخمسون قرشاً لا غير'],
    [1003n, 'EUR', 'فقط عشرة يورو وثلاثة سنتات لا غير'],
  ] as const)('%s %s', (minor, currency, words) => {
    expect(amountInWords(minor, currency)).toBe(words);
  });

  it('refuses a negative amount: the voucher kind states the direction', () => {
    expect(() => amountInWords(-100n, 'USD')).toThrow(RangeError);
  });

  it('reads the largest stored amount', () => {
    expect(amountInWords(9223372036854775807n, 'USD')).toMatch(/^فقط .+ لا غير$/);
  });
});
